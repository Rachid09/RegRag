"""Dataset statistics, written to reports/dataset_stats.md.

Usage: `uv run python -m regrag.stats`. Every dataset number in the README comes from here.
"""

import json
from collections import Counter
from pathlib import Path

from regrag.config import DOCS_DIR, RAW_DIR
from regrag.corpus import load_corpus, load_split

REPORT = Path("reports/dataset_stats.md")
EMBED_MAX_TOKENS = 8192  # gemini-embedding-2 input limit


def est_tokens(text: str) -> int:
    """Rough estimate (chars / 4). Exact counts come from the API at ingestion time."""
    return len(text) // 4


def compute() -> list[str]:
    raw_rows = [r for p in DOCS_DIR.glob("*.json") for r in json.loads(p.read_text())]
    empty_rows = sum(not r["Passage"].strip() for r in raw_rows)
    raw_keys = Counter((r["DocumentID"], r["PassageID"]) for r in raw_rows)
    repeated_ids = sum(v > 1 for v in raw_keys.values())
    corpus = load_corpus()
    keys = {p.key for p in corpus}
    splits = {s: load_split(s) for s in ("train", "dev", "test")}

    lines = ["# ObliQA dataset statistics", "", "Generated by `uv run python -m regrag.stats`.", ""]
    lines += [
        "## QA splits",
        "",
        "| split | questions | " + " | ".join(f"{n} psg" for n in range(1, 7)) + " |",
        "|---" * 8 + "|",
    ]
    for name, items in splits.items():
        c = Counter(len(q.gold) for q in items)
        lines.append(
            f"| {name} | {len(items)} | " + " | ".join(str(c[n]) for n in range(1, 7)) + " |"
        )
    total = sum(len(v) for v in splits.values())
    gold = {k for items in splits.values() for q in items for k in q.gold}
    test_gold = {k for q in splits["test"] for k in q.gold}
    seen = {k for s in ("train", "dev") for q in splits[s] for k in q.gold}
    qids = Counter(q.qid for items in splits.values() for q in items)
    texts = Counter(q.question.lower() for items in splits.values() for q in items)
    train_texts = {q.question.lower() for q in splits["train"]}
    qa_fields = Counter(
        k for s in splits for r in json.loads((RAW_DIR / f"ObliQA_{s}.json").read_text()) for k in r
    )
    with_answer = sum(n for k, n in qa_fields.items() if "answer" in k.lower())
    dup_ids = sum(v > 1 for v in qids.values())
    dup_texts = sum(v > 1 for v in texts.values())
    test_in_train = sum(q.question.lower() in train_texts for q in splits["test"])
    lines += [
        "",
        f"- Total questions: {total}",
        f"- QA record fields: {', '.join(sorted(qa_fields))}",
        f"- Records with a reference-answer field: {with_answer}",
        f"- Duplicate QuestionIDs: {dup_ids}; duplicate question texts: {dup_texts}",
        f"- Test questions whose text also appears in train: {test_in_train}",
        f"- Distinct gold passages (all splits): {len(gold)}; "
        f"missing from corpus: {len(gold - keys)}",
        f"- Test gold passages: {len(test_gold)}; "
        f"never linked in train/dev: {len(test_gold - seen)}",
        "",
        "## Corpus",
        "",
        f"- Documents: {len({p.doc_id for p in corpus})}",
        f"- Raw passage rows: {len(raw_rows)}; empty rows: {empty_rows}",
        f"- PassageIDs repeated within a document (merged): {repeated_ids}",
        f"- Passages to index (non-empty, merged): {len(corpus)}",
        f"- Passages with at least one heading attached: {sum(bool(p.headings) for p in corpus)}",
        f"- Estimated tokens (chars/4): {sum(est_tokens(p.text) for p in corpus):,}",
        f"- Passages over {EMBED_MAX_TOKENS} estimated tokens (to be split): "
        + ", ".join(
            f"{p.doc_id}:{p.passage_id}" for p in corpus if est_tokens(p.text) > EMBED_MAX_TOKENS
        ),
        "",
        "| doc | title | passages |",
        "|---|---|---|",
    ]
    per_doc = Counter(p.doc_id for p in corpus)
    titles = {p.doc_id: p.doc_title for p in corpus}
    lines += [f"| {d} | {titles[d]} | {per_doc[d]} |" for d in sorted(per_doc)]
    return lines


def main() -> None:
    if not RAW_DIR.exists():
        raise SystemExit("data/raw not found: run `uv run python -m regrag.download` first")
    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text("\n".join(compute()) + "\n")
    print(REPORT.read_text())


if __name__ == "__main__":
    main()
